import { defineConfig } from 'vite';
import { createReadStream, existsSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';

// Edusim Stages runs its own code plus a few of the main app's modules from src/ one directory up
// (the Model Database's builders, the MP4 writer). Two things follow, the same two HiFi's config
// records:
//
//  * `three` must resolve to ONE copy, the repo root's. A second copy breaks every `instanceof`
//    check between the two, so the alias pins it, which is why the root `npm install` has to have
//    been run first.
//  * the dev server has to be allowed to serve files from outside this directory.
//
// `base: './'` because the app is served from /stages/, one directory down, where the default '/'
// would 404 every asset.
const root = resolve(__dirname, '..');

// The sprite library shows the Model Database's card pictures, which the main app already ships at
// /app/models/thumbs/. In production /stages/ and /app/ are siblings, so the relative address
// ../app/models/thumbs/<id>.webp simply works; in dev this serves the same path from the main app's
// public folder, so nothing has to be copied. Dev only.
const appModels = {
  name: 'stages-app-models',
  apply: 'serve',
  configureServer(server) {
    server.middlewares.use('/app/models/', (req, res, next) => {
      const file = resolve(root, 'public/models', decodeURIComponent(req.url.split('?')[0]).replace(/^\/+/, ''));
      if (!file.startsWith(resolve(root, 'public/models')) || !existsSync(file)) return next();
      res.setHeader('Content-Type', file.endsWith('.webp') ? 'image/webp' : 'image/jpeg');
      createReadStream(file).pipe(res);
    });
  },
};

// OFFLINE (plan, phase 5). The build writes dist/sw.js with a VERSION that changes on every build and
// the list of files to keep: the page, its own code and the whole cartoon library, but not the
// Model Database's builders, which are fetched (and then kept) only if a student opens the Models
// tab. The page is fetched network-first, so a new deploy reaches students on their next visit
// rather than being hidden behind a stale copy.
const serviceWorker = {
  name: 'stages-service-worker',
  apply: 'build',
  closeBundle() {
    const dist = resolve(__dirname, 'dist');
    const files = [];
    const walk = (dir) => {
      for (const f of readdirSync(dir)) {
        const full = join(dir, f);
        if (statSync(full).isDirectory()) walk(full);
        else files.push(relative(dist, full).split('\\').join('/'));
      }
    };
    walk(dist);
    const core = /^assets\/(index|Gallery|Tutorials|VideoExport|text|tutorials|kit|StudioAudio|Mp4Muxer|soundLibrary)-[\w-]+\.(js|css)$/;
    const keep = files.filter((f) => f !== 'sw.js' && (!f.startsWith('assets/') || core.test(f) || f.endsWith('.css')));
    const version = new Date().toISOString();
    writeFileSync(join(dist, 'sw.js'), `// GENERATED by Stages/vite.config.js on every build. Do not edit.
const VERSION = ${JSON.stringify(version)};
const CACHE = 'edusim-stages-' + VERSION;
const PRECACHE = ${JSON.stringify(['./', ...keep])};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('edusim-stages-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== location.origin) return;
  const scope = new URL(self.registration.scope);
  if (!url.pathname.startsWith(scope.pathname)) return;
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).then((res) => {
      const copy = res.clone();
      caches.open(CACHE).then((c) => c.put('./', copy));
      return res;
    }).catch(() => caches.match('./')));
    return;
  }
  e.respondWith(caches.match(req).then((hit) => hit || fetch(req).then((res) => {
    if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
    return res;
  })));
});
`);
    console.log(`sw.js: ${keep.length} files kept for offline, version ${version}`);
  },
};

export default defineConfig({
  base: './',
  plugins: [appModels, serviceWorker],
  resolve: {
    alias: [{ find: /^three$/, replacement: resolve(root, 'node_modules/three') }, { find: /^three\//, replacement: `${resolve(root, 'node_modules/three')}/` }],
    dedupe: ['three'],
  },
  server: { port: 5193, fs: { allow: [root] } },
  optimizeDeps: {
    include: ['three', 'three/examples/jsm/utils/BufferGeometryUtils.js'],
  },
  build: { chunkSizeWarningLimit: 12000 },
});
