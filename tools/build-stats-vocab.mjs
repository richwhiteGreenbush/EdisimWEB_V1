// Writes EdusimWorldDatabase/lib/stats-vocab.php, the fixed lists the stats endpoint accepts.
//
//   node tools/build-stats-vocab.mjs
//
// The endpoint takes writes from anybody with no login, so it stores a world, object or
// block name only if it is on these lists and `other` if it is not. That is what makes "only
// names off a fixed list can be stored" a fact about the server rather than a promise about
// the client. They are generated from the app's own tables because a copy by hand would drift.
//
// Forgetting to re-run this after adding a world, prop or block is safe: the new name counts
// as `other` until it is, and no count is lost.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const { BLOCK_DEFS } = await import('../src/BlockDefs.js');
const { JS_RUNTIME_NAMES } = await import('../src/JsProgram.js');
const { PRIMITIVE_SHAPES } = await import('../src/Primitives.js');
const { PROP_BUILDERS } = await import('../src/props/index.js');
const { PRESET_WORLDS } = await import('../src/WorldPresets.js');
const { MODELS } = await import('../src/models/catalog.js');

const php = (value) => `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const list = (values) => `[${[...values].sort().map(php).join(', ')}]`;
const map = (entries) => `[\n${entries.map(([k, v]) => `        ${php(k)} => ${php(v)},`).join('\n')}\n    ]`;

const presets = Object.entries(PRESET_WORLDS).map(([key, world]) => [key, world.label ?? key]);

const out = `<?php
declare(strict_types=1);

// GENERATED by tools/build-stats-vocab.mjs. Do not edit; re-run it instead.
return [
    'words' => ${list(new Set([...Object.keys(BLOCK_DEFS), ...JS_RUNTIME_NAMES]))},
    'shapes' => ${list(PRIMITIVE_SHAPES)},
    'props' => ${list(Object.keys(PROP_BUILDERS))},
    'catalog' => ${list(MODELS.map((model) => model.id))},
    'presets' => ${map(presets)},
];
`;

const target = fileURLToPath(new URL('../EdusimWorldDatabase/lib/stats-vocab.php', import.meta.url));
writeFileSync(target, out);
console.log(`${target}: ${Object.keys(BLOCK_DEFS).length} blocks, ${JS_RUNTIME_NAMES.length} js names, `
  + `${PRIMITIVE_SHAPES.length} shapes, ${Object.keys(PROP_BUILDERS).length} props, ${MODELS.length} catalogue models, ${presets.length} presets`);
