// The block stacks printed here are the kit's real starter programs (src/models/programs.js), and
// the numbers in the activities are the kit's own dimensions (src/models/town/TownKit.js). Links to
// the app are absolute with a trailing slash, for the reason every other page under docs/ gives.
import { writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { MODELS } from '../src/models/catalog.js';

const APP = 'https://edusim3dweb.com/app/';
const MY_WORLD = `${APP}?world=8`;
const esc = (text) => String(text).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const kit = MODELS.filter((m) => m.category === 'citykit');
const title = (id) => {
  const model = kit.find((m) => m.id === id);
  if (!model) throw new Error(`No city model called ${id}`);
  return esc(model.title);
};
const stack = (...rows) => `<ul class="blocks mini">${rows.map(([kind, text, depth = 0]) => `<li class="${kind}${depth ? ` d${depth}` : ''}">${esc(text)}</li>`).join('')}</ul>`;

const GROUPS = [
  ['Homes and shops', ['row-house', 'apartment-building', 'office-tower', 'corner-grocery', 'city-diner', 'post-office']],
  ['Community buildings', ['fire-station', 'police-station', 'city-hospital', 'city-hall', 'public-library', 'elementary-school']],
  ['Vehicles', ['city-bus', 'school-bus', 'fire-engine', 'garbage-truck', 'police-car', 'city-ambulance', 'city-taxi', 'delivery-truck']],
  ['Streets', ['road-straight', 'road-intersection', 'traffic-light', 'street-lamp', 'fire-hydrant', 'bus-stop']],
  ['Parks and utilities', ['city-park', 'recycling-bins', 'solar-panel-array', 'water-tower']],
];
const listed = GROUPS.flatMap(([, ids]) => ids);
if (listed.length !== kit.length || new Set(listed).size !== kit.length) throw new Error('The kit list and the table disagree');

const kitRows = GROUPS.map(([name, ids]) => `
        <div class="vk-group">
          <h3>${esc(name)}</h3>
          <div class="vk-row">${ids.map((id) => `
            <a class="vk-piece" href="models.html#model-${esc(id)}"><img src="../assets/models/${esc(id)}.webp" alt="" loading="lazy" width="120" height="120" /><span>${title(id)}</span></a>`).join('')}
          </div>
        </div>`).join('');

// Pictures of a whole city, if tools/check-city.mjs has taken them.
