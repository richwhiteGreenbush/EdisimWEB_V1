function code(src, level, objectNames = []) {
  const r = compile(src, level, { objectNames });
  const bad = r.diagnostics.filter((d) => d.code !== 'W301');
  if (bad.length) throw new Error(`card sample has a problem at level ${level}:\n${src}\n${bad.map((d) => `${d.code} ${d.title}`).join('\n')}`);
  return `<div class="code" data-level="${level}">${highlight(src.replace(/\n$/, ''))}</div>`;
}


// The command table, one section per block category, in the palette's own order and colours.
function commandTable() {
  const one = commandLines(1);
  const two = commandLines(2);
  const out = [];
  for (const category of ['control', 'motion', 'look', 'math']) {
    const rows = one.map((c, i) => ({ c, pro: two[i] })).filter(({ c }) => c.category === category);
    out.push(`    <section class="qs">
      <div class="qs-head"><span class="qs-num" style="background:${CATEGORIES[category].fill}">${CATEGORIES[category].name[0]}</span>
        <div><h3>${CATEGORIES[category].name}</h3></div>
      </div>
      <table class="forms">
        <thead><tr><th>Basic Beginner</th><th>Basic Pro</th></tr></thead>
        <tbody>
${rows.map(({ c, pro }) => `          <tr><td><code class="hl">${highlight(c.label)}</code></td><td><code class="hl">${highlight(pro.label)}</code></td></tr>`).join('\n')}
        </tbody>
      </table>
    </section>`);
  }
  return out.join('\n\n');
}

